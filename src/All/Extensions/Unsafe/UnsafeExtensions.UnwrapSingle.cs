using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading.Tasks;
using Wrap.Exceptions;

namespace Wrap.Extensions;

public static partial class UnsafeExtensions
{
	/// <summary>
	/// Get the only item in the list held by <paramref name="this"/>, or run <paramref name="fLeft"/>
	/// if it holds a <typeparamref name="TLeft"/> value.
	/// </summary>
	/// <remarks>
	/// <para>
	/// Unlike <see cref="Unwrap{TEither, TLeft, TRight}(Unsafe{TEither, TLeft, TRight})"/>, a <typeparamref name="TLeft"/>
	/// value (for example <see cref="None"/> or a <see cref="Failure"/>) does not throw: <paramref name="fLeft"/>
	/// is called instead. It also lets C# work out <typeparamref name="TSingle"/>, which it cannot do from the
	/// constraint on <typeparamref name="TRight"/>.
	/// </para>
	/// <para>
	/// Only the first two items of the list are read.
	/// </para>
	/// </remarks>
	/// <typeparam name="TEither">Either implementation type.</typeparam>
	/// <typeparam name="TLeft">Left (error / invalid) value type.</typeparam>
	/// <typeparam name="TRight">Right (correct / valid) value type: a list of <typeparamref name="TSingle"/>.</typeparam>
	/// <typeparam name="TSingle">List item type.</typeparam>
	/// <param name="this">Unsafe object.</param>
	/// <param name="fLeft">Function to generate a value if <paramref name="this"/> holds a <typeparamref name="TLeft"/> value.</param>
	/// <returns>The only item in the list, or the value generated by <paramref name="fLeft"/>.</returns>
	/// <exception cref="UnsafeUnwrapSingleException{TRight, TSingle}">Thrown when the list is empty or has more than one item.</exception>
	public static TSingle UnwrapSingle<TEither, TLeft, TRight, TSingle>(this Unsafe<TEither, TLeft, TRight> @this, Func<TLeft, TSingle> fLeft)
		where TEither : IEither<TLeft, TRight>
		where TRight : IEnumerable<TSingle> =>
		@this.Value.TryGetLeft(out var left) switch
		{
			true =>
				fLeft(left),

			false =>
				@this.Value.TryGetRight(out var right) && right.Take(2).ToArray() is [var single]
					? single
					: throw new UnsafeUnwrapSingleException<TRight, TSingle>()
		};

	/// <inheritdoc cref="UnwrapSingle{TEither, TLeft, TRight, TSingle}(Unsafe{TEither, TLeft, TRight}, Func{TLeft, TSingle})"/>
	public static Task<TSingle> UnwrapSingleAsync<TEither, TLeft, TRight, TSingle>(this Task<Unsafe<TEither, TLeft, TRight>> @this, Func<TLeft, TSingle> fLeft)
		where TEither : IEither<TLeft, TRight>
		where TRight : IEnumerable<TSingle> =>
		@this.Then(x => x.UnwrapSingle(fLeft));
}
