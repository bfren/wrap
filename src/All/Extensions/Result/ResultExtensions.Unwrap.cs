	/// <summary>
	/// Unwrap the value contained in <paramref name="this"/>.
	/// </summary>
	/// <remarks>
	/// <para>
	/// Provides access to the value wrapped by a <see cref="Result{T}"/> object.
	/// </para>
	/// <para>
	/// You need to provide a default value via <paramref name="ifFailed"/> in case
	/// <paramref name="this"/> is <see cref="Failure"/>.
	/// </para>
	/// </remarks>
	/// <typeparam name="T">Ok value type.</typeparam>
	/// <param name="this">Result object.</param>
	/// <param name="ifFailed">Function to generate a value if <paramref name="this"/> is <see cref="Failure"/>.</param>
	/// <returns>The value of <paramref name="this"/> or generated by <paramref name="ifFailed"/>.</returns>
	public static Task<T> UnwrapAsync<T>(this Result<T> @this, Func<Failure, Task<T>> ifFailed) =>
		R.MatchAsync(@this,
			fFail: ifFailed,
			fOk: x => x
		);

	/// <inheritdoc cref="UnwrapAsync{T}(Result{T}, Func{Failure, Task{T}})"/>
	public static Task<T> UnwrapAsync<T>(this Task<Result<T>> @this, Func<Failure, T> ifFailed) =>
		R.MatchAsync(@this,
			fFail: ifFailed,
			fOk: async x => x
		);

	/// <inheritdoc cref="UnwrapAsync{T}(Result{T}, Func{Failure, Task{T}})"/>
	public static Task<T> UnwrapAsync<T>(this Task<Result<T>> @this, Func<Failure, Task<T>> ifFailed) =>
		R.MatchAsync(@this,
			fFail: ifFailed,
			fOk: async x => x
		);

	#endregion

