	/// <summary>
	/// Unwrap the value contained in <paramref name="this"/>.
	/// </summary>
	/// <remarks>
	/// <para>
	/// Provides access to the value wrapped by a <see cref="Result{T}"/> object.
	/// </para>
	/// <para>
	/// You need to provide a default value via <paramref name="returnThis"/> in case
	/// <paramref name="this"/> is <see cref="Failure"/>.
	/// </para>
	/// </remarks>
	/// <typeparam name="T">Ok value type.</typeparam>
	/// <param name="this">Result object.</param>
	/// <param name="ifFailed">Function to handle a Failure.</param>
	/// <param name="returnThis">Function to return a value on a Failure.</param>
	/// <returns>The value of <paramref name="this"/> or generated by <paramref name="returnThis"/>.</returns>
	public static async Task<T> UnwrapAsync<T>(this Result<T> @this, Func<Failure, Task> ifFailed, Func<Task<T>> returnThis)
	{
		switch (@this)
		{
			case Ok<T> x:
				return x.Value;

			case Failure f:
				await ifFailed(f);
				return await returnThis();

			// IDE0010 does not treat the union cases as complete, so it needs this arm
			default:
				return await returnThis();
		}
	}

	/// <inheritdoc cref="UnwrapAsync{T}(Result{T}, Func{Failure, Task}, Func{Task{T}})"/>
