	#region Without Return Value

	/// <summary>
	/// Run an action based on the value of <paramref name="maybe"/>.
	/// </summary>
	/// <remarks>
	/// <para>
	/// This is shorthand for a <c>switch</c> over the <see cref="Some{T}"/> and <see cref="Wrap.None"/> cases
	/// that passes the unwrapped value to <paramref name="fSome"/>. Both approaches make you handle both cases:
	/// here through the required arguments, and in a <c>switch</c> through the compiler's exhaustiveness check.
	/// </para>
	/// </remarks>
	/// <typeparam name="T">Some value type.</typeparam>
	/// <param name="maybe">Maybe object.</param>
	/// <param name="fNone">Action to run when <paramref name="maybe"/> is <see cref="Wrap.None"/>.</param>
	/// <param name="fSome">Action to run with the value when <paramref name="maybe"/> is <see cref="Some{T}"/>.</param>
	public static void Match<T>(Maybe<T> maybe, Action fNone, Action<T> fSome)
	{
		switch (maybe)
		{
			case global::Wrap.None:
				fNone();
				return;

			case Some<T> x:
				fSome(x.Value);
				return;

			// IDE0010 does not treat the union cases as complete, so it needs this arm
			default:
				break;
		}
	}

	/// <inheritdoc cref="Match{T}(Maybe{T}, Action, Action{T})"/>
	public static async Task MatchAsync<T>(Maybe<T> maybe, Action fNone, Func<T, Task> fSome)
	{
		switch (maybe)
		{
			case global::Wrap.None:
				fNone();
				return;

			case Some<T> x:
				await fSome(x.Value);
				return;

			// IDE0010 does not treat the union cases as complete, so it needs this arm
			default:
				break;
		}
	}

	/// <inheritdoc cref="Match{T}(Maybe{T}, Action, Action{T})"/>
	public static async Task MatchAsync<T>(Maybe<T> maybe, Func<Task> fNone, Action<T> fSome)
	{
